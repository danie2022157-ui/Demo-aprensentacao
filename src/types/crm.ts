export type PipelineStage =
  | 'novo_interessado'
  | 'primeiro_contato'
  | 'orcamento_enviado'
  | 'negociacao'
  | 'fechado';

export type Priority = 'alta' | 'media' | 'baixa';

export type FollowUpStatus = 'pendente' | 'concluido';

export type ConversationChannel = 'whatsapp' | 'telefone' | 'email' | 'reuniao';

export type ClientStatus = 'ativo' | 'lead' | 'negociacao' | 'inativo';

export type ProposalStatus =
  | 'aguardando_retorno'
  | 'em_revisao'
  | 'aprovado'
  | 'perdido';

export type LossReason =
  | 'sem_retorno'
  | 'preco'
  | 'concorrencia'
  | 'prazo'
  | 'projeto_adiado';

export type FinancialEntryType = 'receber' | 'despesa';
export type FinancialEntryStatus = 'pendente' | 'pago';

export interface Client {
  id: string;
  company: string;
  contactName: string;
  role: string;
  email: string;
  phone: string;
  segment: string;
  city: string;
  owner: string;
  status: ClientStatus;
  notes: string;
  createdAt: string;
}

export interface Opportunity {
  id: string;
  clientId: string;
  title: string;
  value: number;
  stage: PipelineStage;
  probability: number;
  owner: string;
  expectedCloseDate: string;
  recovered?: boolean;
  createdAt: string;
  updatedAt: string;
}

export interface Proposal {
  id: string;
  code: string;
  clientId: string;
  opportunityId?: string;
  title: string;
  value: number;
  sentDate: string; // YYYY-MM-DD
  expectedReturnDate: string; // YYYY-MM-DD
  owner: string;
  status: ProposalStatus;
  lossReason?: LossReason;
  notes: string;
}

export interface FinancialEntry {
  id: string;
  description: string;
  clientId?: string;
  category: string;
  type: FinancialEntryType;
  amount: number;
  dueDate: string; // YYYY-MM-DD
  status: FinancialEntryStatus;
  paidAt?: string;
}

export interface FollowUpTask {
  id: string;
  clientId: string;
  opportunityId?: string;
  title: string;
  contextLabel: string;
  dueDate: string; // YYYY-MM-DD
  dueTime: string; // HH:mm
  priority: Priority;
  owner: string;
  status: FollowUpStatus;
  channel: ConversationChannel;
  notes: string;
  autoGenerated?: boolean;
  requiresManualApproval: boolean;
  recurrenceDays?: number;
  completedAt?: string;
  outcome?: 'respondeu' | 'sem_resposta' | 'concluido_padrao';
}

export interface ConversationLog {
  id: string;
  clientId: string;
  opportunityId?: string;
  channel: ConversationChannel;
  direction: 'enviado' | 'recebido' | 'interno';
  summary: string;
  owner: string;
  timestamp: string; // ISO string
}

export interface FollowUpRule {
  id: string;
  name: string;
  triggerStage: PipelineStage;
  enabled: boolean;
  delayDays: number;
  delayHours: number;
  recurrenceDays: number;
  maxReminders: number;
  defaultPriority: Priority;
  defaultTaskTitle: string;
  defaultContextLabel: string;
  requiresManualApproval: boolean;
}

export interface MessageTemplate {
  id: string;
  name: string;
  stage: PipelineStage | 'geral';
  channel: 'whatsapp' | 'email';
  subject?: string;
  body: string;
  updatedAt: string;
}

export interface WhatsAppConfig {
  mode: 'planejado' | 'homologacao';
  requireManualApproval: boolean;
  businessPhoneDisplay: string;
  webhookStatus: string;
}

export interface MonthlyRevenuePoint {
  month: string;
  revenue: number;
  pipeline: number;
  deals: number;
}

export interface DiagnosticSubmission {
  id: string;
  companyName: string;
  contactName: string;
  whatsapp: string;
  segment: string;
  mainPain: string;
  simulatedPotential: number;
  simulatedRecovery: number;
  createdAt: string;
}

export interface CrmState {
  referenceDate: string; // YYYY-MM-DD deterministic demo anchor
  clients: Client[];
  opportunities: Opportunity[];
  proposals: Proposal[];
  financialEntries: FinancialEntry[];
  tasks: FollowUpTask[];
  conversations: ConversationLog[];
  rules: FollowUpRule[];
  templates: MessageTemplate[];
  whatsappConfig: WhatsAppConfig;
  monthlyHistory: MonthlyRevenuePoint[];
  diagnosticRequests: DiagnosticSubmission[];
}

export interface FollowUpSummary {
  pending: number;
  overdue: number;
  completed: number;
  today: number;
}

export interface StageConfig {
  id: PipelineStage;
  label: string;
  shortLabel: string;
  defaultProbability: number;
  accentHex: string;
}

